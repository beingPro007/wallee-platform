-- Read-only admin observability. Service role writes telemetry; no browser access.
create table if not exists public.ops_runs (
  id uuid primary key,
  kind text not null check (kind in ('ingestion','upscale','desktop','publish')),
  reference text,
  status text not null default 'running' check (status in ('running','succeeded','partial','failed')),
  stage text not null default 'accepted',
  message text,
  details jsonb not null default '{}',
  started_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  finished_at timestamptz
);
create index if not exists ops_runs_started_idx on public.ops_runs(started_at desc);
create index if not exists ops_runs_status_idx on public.ops_runs(status,updated_at desc);
create table if not exists public.ops_events (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.ops_runs(id) on delete cascade,
  stage text not null,
  message text not null,
  level text not null default 'info' check (level in ('info','warning','error')),
  details jsonb not null default '{}',
  created_at timestamptz not null default now()
);
create index if not exists ops_events_run_idx on public.ops_events(run_id,created_at);
alter table public.ops_runs enable row level security;
alter table public.ops_events enable row level security;
revoke all on public.ops_runs,public.ops_events from anon,authenticated;
grant all on public.ops_runs,public.ops_events to service_role;
grant usage,select on sequence public.ops_events_id_seq to service_role;

create or replace function public.ops_dashboard_summary()
returns jsonb language sql stable security definer set search_path = pg_catalog, public as $$
 select jsonb_build_object(
  'database_images',(select count(*) from public.wallpapers),
  'queue',(select coalesce(jsonb_object_agg(status,n),'{}') from (select status,count(*) n from public.upscale_queue group by status) q),
  'operations_24h',(select coalesce(jsonb_object_agg(status,n),'{}') from (select status,count(*) n from public.ops_runs where started_at>now()-interval '24 hours' group by status) r),
  'tracking_since',(select min(started_at) from public.ops_runs),
  'schedules',(select coalesce(jsonb_agg(jsonb_build_object('id',j.jobid,'name',coalesce(j.jobname,'Scheduled task '||j.jobid),'schedule',j.schedule,'active',j.active,'last_status',d.status,'last_finished',d.end_time)),'[]') from cron.job j left join lateral (select status,end_time from cron.job_run_details where jobid=j.jobid order by start_time desc limit 1) d on true)
 );
$$;
revoke all on function public.ops_dashboard_summary() from public,anon,authenticated;
grant execute on function public.ops_dashboard_summary() to service_role;
